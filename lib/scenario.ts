export function findScenario(id: string) {
  return SCENARIOS.find((s) => s.id === id) ?? SCENARIOS[0];
}

export function turnAt(scenario: Scenario, index: number) {
  return scenario.turns[Math.min(index, scenario.turns.length - 1)];
}
